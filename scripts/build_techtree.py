"""Build the Markdown the model loads: one compact index per era (core + era file)
and one era-independent reference file per category.

Usage:
    python scripts/build_techtree.py                 # all eras
    python scripts/build_techtree.py europe-1490-florence
    python scripts/build_techtree.py --check         # validate only, non-zero on problems
"""

from __future__ import annotations

import argparse
import re
import sys

from techtree import ERAS, ROOT, era_status, load_core, load_era, validate

OUT = ROOT / "techtree" / "generated"
SITE_URL = "https://blueprintsfromtomorrow.com"
MAKE_ORDER = ["easy", "medium", "hard", "very-hard", "impossible", "?"]


def one_line(text) -> str:
    return " ".join(str(text).split())


def deps(t: dict) -> str:
    parts = []
    if t.get("requires"):
        parts.append("needs " + ", ".join(t["requires"]))
    if t.get("helps"):
        parts.append("helped by " + ", ".join(t["helps"]))
    return "; ".join(parts)


def _render_category_index(core: dict, era_id: str) -> list[str]:
    """Compact ~1.5 KB map of all 17 categories placed near the top so even a truncated fetch
    shows everything available and gives direct URLs to small (5-15 KB) on-demand slices."""
    lines = [
        "## Quick index (what's in this file & small on-demand slices)",
        f"Below: `People`, `Events and timeline`, `Quest hooks`, and all {len(core['technologies'])} local tech statuses across 17 categories.",
        "If anything below is truncated, fetch only the category slice (5–15 KB) or deep tech catalog (3–6 KB) you need:",
    ]
    for cat_id, cat_name in core["categories"].items():
        count = sum(1 for t in core["technologies"] if t["category"] == cat_id)
        if not count:
            continue
        slice_url = f"{SITE_URL}/techtree/generated/{era_id}/{cat_id}.md"
        cat_url = f"{SITE_URL}/techtree/generated/catalog/{cat_id}.md"
        lines.append(f"- {cat_name} (`{cat_id}`, {count}): [era slice]({slice_url}) · [deep links]({cat_url})")
    lines.append("")
    return lines


def _render_era_context(era: dict) -> list[str]:
    """People, events, and quest hooks — kept near the top so truncation never drops them."""
    lines: list[str] = []
    add = lines.append
    if era.get("people"):
        add("## People")
        for p in era["people"]:
            extra = f" — {one_line(p['note'])}" if p.get("note") else ""
            knows = f" Knows: {one_line(p['knows'])}." if p.get("knows") else ""
            add(f"- **{p['name']}**: {one_line(p['role'])}.{knows}{extra}")
        add("")
    if era.get("events"):
        add("## Events and timeline")
        for e in era["events"]:
            add(f"- {e}")
        add("")
    if era.get("quest_hooks"):
        add("## Quest hooks")
        for q in era["quest_hooks"]:
            add(f"- {q}")
        add("")
    return lines


def render_era_briefing(core: dict, era: dict) -> str:
    """Compact ~20 KB era briefing for agents with strict web-fetch size limits:
    worldview, category index, people, events, and quest hooks."""
    era_id = era["era"]
    lines: list[str] = []
    add = lines.append
    add(f"# Era briefing: {era['title']}")
    add("")
    add(f"<!-- generated by scripts/build_techtree.py from eras/{era_id}.yaml — do not edit -->")
    add("")
    levels = " · ".join(f"K{k} {v}" for k, v in core["knowledge_levels"].items())
    add(f"Region: {era['region']}. Year: {era['year']}. Knowledge: {levels}.")
    add(f"Compact briefing (~20 KB) for web-fetch tools that truncate the full guide ([`{era_id}.md`]({SITE_URL}/techtree/generated/{era_id}.md)).")
    add("Fetch individual category slices below (5–15 KB each) on demand as topics come up in play.")
    add("")
    add("## Worldview")
    add(one_line(era["worldview"]))
    add("")
    lines.extend(_render_category_index(core, era_id))
    lines.extend(_render_era_context(era))
    return "\n".join(lines)


def render(core: dict, era: dict) -> str:
    """Full self-contained era guide (~30-35k tokens): worldview, quick category index,
    people, events, quest hooks, all 510 local statuses with notes/materials, and catalog links."""
    era_id = era["era"]
    lines: list[str] = []
    add = lines.append
    add(f"# Tech status: {era['title']}")
    add("")
    add(f"<!-- generated by scripts/build_techtree.py from techtree/core/ + eras/{era_id}.yaml — do not edit -->")
    add("")
    levels = " · ".join(f"K{k} {v}" for k, v in core["knowledge_levels"].items())
    add(f"Region: {era['region']}. Year: {era['year']}. Knowledge: {levels}.")
    add("Format: `id` (Name): K-level, use (omitted when K0/none), make (producibility), acc (acceptance), local note, local hooks, elsewhere.")
    add(f"This file is self-contained for play. If your fetch tool truncates this file, use the quick index below or load the compact [era briefing]({SITE_URL}/techtree/generated/{era_id}/briefing.md) (~20 KB) and fetch per-category slices on demand.")
    add("For deep mechanism checks (`pitfalls`) or evaluation literature (`sources`), open a category's **deep links** catalog below and fetch `tech/<id>.md` (~2 KB).")
    add("")
    add("## Worldview")
    add(one_line(era["worldview"]))
    add("")
    lines.extend(_render_category_index(core, era_id))
    lines.extend(_render_era_context(era))

    for cat_id, cat_name in core["categories"].items():
        techs = [t for t in core["technologies"] if t["category"] == cat_id]
        if not techs:
            continue
        cat_url = f"{SITE_URL}/techtree/generated/catalog/{cat_id}.md"
        add(f"## {cat_name} (`{cat_id}`) — [deep tech links]({cat_url})")
        ranked = sorted(
            techs,
            key=lambda t: (
                -era_status(era, t["id"])["knowledge"],
                MAKE_ORDER.index(era_status(era, t["id"]).get("producibility", "?")),
                t["id"],
            ),
        )
        for t in ranked:
            st = era_status(era, t["id"])
            parts = [f"K{st['knowledge']}"]
            if st["use"] != "none" or st["knowledge"] > 0:
                parts.append(f"use:{st['use']}")
            if "producibility" in st:
                parts.append(f"make:{st['producibility']}")
            if "acceptance" in st:
                parts.append(f"acc:{st['acceptance']}")
            line = f"- `{t['id']}` ({t['name']}): {' '.join(parts)}"
            if st.get("note"):
                line += f". {one_line(st['note'])}"
            if st.get("local"):
                line += f" Local: {'; '.join(st['local'])}."
            if st.get("elsewhere"):
                line += f" Elsewhere: {'; '.join(st['elsewhere'])}."
            add(line)
        add("")
    return "\n".join(lines)


def render_era_category(core: dict, era: dict, cat_id: str) -> str:
    """Local status of one category in one era."""
    lines = [
        f"# {era['title']} – {core['categories'][cat_id]}",
        "",
        f"<!-- generated by scripts/build_techtree.py from eras/{era['era']}.yaml — do not edit -->",
        "",
        "K = knowledge level · use = none/wrong/partial/correct · make = producibility with local means · accept = acceptance.",
        "",
    ]
    for t in core["technologies"]:
        if t["category"] != cat_id:
            continue
        st = era_status(era, t["id"])
        parts = [f"K{st['knowledge']}", f"use {st['use']}"]
        if "producibility" in st:
            parts.append(f"make {st['producibility']}")
        if "acceptance" in st:
            parts.append(f"accept {st['acceptance']}")
        tech_url = f"{SITE_URL}/techtree/generated/tech/{t['id']}.md"
        line = f"- **{t['name']}** [`{t['id']}`]({tech_url}) — {', '.join(parts)}"
        if st.get("note"):
            line += f". {one_line(st['note'])}"
        if st.get("local"):
            line += f" Local: {'; '.join(st['local'])}."
        if st.get("elsewhere"):
            line += f" Elsewhere: {'; '.join(st['elsewhere'])}."
        lines.append(line)
    return "\n".join(lines) + "\n"


def render_all_techs(core: dict) -> str:
    """Self-contained ~22k-token guide for any custom era/culture without an era file:
    all 510 technologies with hard prerequisites and regional first-appearance dates."""
    lines = [
        "# Complete Tech Tree Guide (All 510 Technologies · Custom Eras & Cultures)",
        "",
        "<!-- generated by scripts/build_techtree.py from techtree/core/*.yaml — do not edit -->",
        "",
        "Load this file once at campaign start when playing any custom time, place, or culture without a predefined era file.",
        "It lists all 510 technologies with hard prerequisites (`needs`) and first-appearance dates across 12 world regions to prevent anachronisms.",
        "For full `pitfalls`, `Core idea`, and evaluation `sources`, open a category's **deep links** catalog below and fetch `tech/<id>.md` (~2 KB).",
        "",
    ]
    add = lines.append
    for cat_id, cat_name in core["categories"].items():
        techs = [t for t in core["technologies"] if t["category"] == cat_id]
        if not techs:
            continue
        cat_url = f"{SITE_URL}/techtree/generated/catalog/{cat_id}.md"
        add(f"## {cat_name} (`{cat_id}`) — [deep tech links]({cat_url})")
        for t in techs:
            req = f" [needs: {', '.join(t['requires'])}]" if t.get("requires") else ""
            hy = []
            for r, h in (t.get("history") or {}).items():
                head = re.split(r"\s+[–—]\s+", one_line(h), maxsplit=1)[0].strip()
                if len(head) > 36:
                    head = head[:35].rstrip() + "…"
                hy.append(f"{r}: {head}")
            hstr = f" — {'; '.join(hy)}" if hy else ""
            add(f"- **{t['name']}** `{t['id']}`{req}{hstr}")
        add("")
    return "\n".join(lines)


def render_catalog(core: dict, cat_id: str) -> str:
    """Compact era-independent index of one category with literal links to each tech file.
    Used for custom eras/cultures without an era file and for strict web_fetch agents."""
    lines = [
        f"# Tech Catalog: {core['categories'][cat_id]} (`{cat_id}`)",
        "",
        f"<!-- generated by scripts/build_techtree.py from techtree/core/{cat_id}.yaml — do not edit -->",
        "",
        "Era-independent list of technologies in this category. Open any link for core idea, pitfalls, dependencies, regional history, and sources.",
        "",
    ]
    for t in core["technologies"]:
        if t["category"] != cat_id:
            continue
        tech_url = f"{SITE_URL}/techtree/generated/tech/{t['id']}.md"
        req = f" (needs: {', '.join(t['requires'])})" if t.get("requires") else ""
        lines.append(f"- **{t['name']}** [`{t['id']}`]({tech_url}){req}")
    return "\n".join(lines) + "\n"


def render_tech(core: dict, t: dict) -> str:
    """Compact era-independent reference for a single technology (for low-token lookup)."""
    cat_id = t["category"]
    cat_name = core["categories"][cat_id]
    lines = [
        f"# {t['name']} (`{t['id']}`)",
        "",
        f"<!-- generated by scripts/build_techtree.py from techtree/core/{cat_id}.yaml — do not edit -->",
        "",
        f"- Category: {cat_name} (`{cat_id}`)",
    ]
    if deps(t):
        lines.append(f"- Deps: {deps(t)}")
    lines.append(f"- Core idea: {one_line(t['explain'])}")
    if t.get("pitfalls"):
        lines.append("- Pitfalls:")
        for pit in t["pitfalls"]:
            lines.append(f"  - {one_line(pit)}")
    hist = "; ".join(f"{r}: {one_line(h)}" for r, h in (t.get("history") or {}).items())
    if hist:
        lines.append(f"- History: {hist}")
    if t.get("sources"):
        lines.append("- Read:")
        for src in t["sources"]:
            lines.append(f"  - {src}")
    return "\n".join(lines) + "\n"


def render_reference(core: dict, cat_id: str) -> str:
    """Era-independent detail for one category."""
    lines = [
        f"# Reference: {core['categories'][cat_id]}",
        "",
        f"<!-- generated by scripts/build_techtree.py from techtree/core/{cat_id}.yaml — do not edit -->",
        "",
    ]
    add = lines.append
    for t in core["technologies"]:
        if t["category"] != cat_id:
            continue
        add(f"## {t['name']} `{t['id']}`")
        if deps(t):
            add(f"- Deps: {deps(t)}")
        add(f"- Core idea: {one_line(t['explain'])}")
        if t.get("pitfalls"):
            add(f"- Pitfalls: {' | '.join(map(one_line, t['pitfalls']))}")
        hist = "; ".join(f"{r}: {one_line(h)}" for r, h in (t.get("history") or {}).items())
        if hist:
            add(f"- History: {hist}")
        if t.get("sources"):
            add(f"- Read: {' | '.join(t['sources'])}")
        add("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("eras", nargs="*", help="era ids (default: all)")
    ap.add_argument("--check", action="store_true", help="validate only")
    args = ap.parse_args()

    core = load_core()
    era_ids = args.eras or [p.stem for p in sorted(ERAS.glob("*.yaml"))]
    problems = validate(core)
    if not args.check:
        OUT.mkdir(parents=True, exist_ok=True)
        all_techs_text = render_all_techs(core)
        (OUT / "all-techs.md").write_text(all_techs_text, encoding="utf-8")
        print(f"wrote {(OUT / 'all-techs.md').relative_to(ROOT)} (~{len(all_techs_text) // 4} tokens)")
        (OUT / "reference").mkdir(parents=True, exist_ok=True)
        (OUT / "catalog").mkdir(parents=True, exist_ok=True)
        for cat_id in core["categories"]:
            (OUT / "reference" / f"{cat_id}.md").write_text(render_reference(core, cat_id), encoding="utf-8")
            (OUT / "catalog" / f"{cat_id}.md").write_text(render_catalog(core, cat_id), encoding="utf-8")
        tech_dir = OUT / "tech"
        tech_dir.mkdir(parents=True, exist_ok=True)
        expected_tech_files = {f"{t['id']}.md" for t in core["technologies"]}
        for stale in tech_dir.glob("*.md"):
            if stale.name not in expected_tech_files:
                stale.unlink()
        for t in core["technologies"]:
            (tech_dir / f"{t['id']}.md").write_text(render_tech(core, t), encoding="utf-8")
        print(f"wrote {len(core['technologies'])} per-tech files in {(tech_dir).relative_to(ROOT)}")
    for era_id in era_ids:
        era = load_era(era_id)
        problems += validate(core, era)
        if not args.check:
            OUT.mkdir(parents=True, exist_ok=True)
            text = render(core, era)
            path = OUT / f"{era_id}.md"
            path.write_text(text + "\n", encoding="utf-8")
            (OUT / era_id).mkdir(exist_ok=True)
            (OUT / era_id / "briefing.md").write_text(render_era_briefing(core, era), encoding="utf-8")
            for cat_id in core["categories"]:
                detail = render_era_category(core, era, cat_id)
                (OUT / era_id / f"{cat_id}.md").write_text(detail, encoding="utf-8")
            approx_tokens = len(text) // 4
            print(f"wrote {path.relative_to(ROOT)} (~{approx_tokens} tokens)")
    for p in problems:
        print(f"PROBLEM: {p}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
